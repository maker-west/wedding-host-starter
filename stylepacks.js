  /* 本地引擎取句：按档 + 环节，没有就返回 null */
  function linesFor(packId, segKey) {
    const p = byId(packId);
    if (!p || !p.lines) return null;
    return p.lines[segKey] || null;
  }

  function prefsOf(packId) {
    const p = byId(packId);
    return p && p.prefs ? Object.assign({}, p.prefs) : null;
  }

  /* 套装骨架对照：返回 {have:[], missing:[], extra:[]} */
  function frameDiff(segKeys) {
    const have = [], missing = [], extra = [];
    const keys = segKeys || [];
    FRAME.forEach(f => {
      if (!f.seg) { missing.push(f); return; }
      if (keys.indexOf(f.seg) >= 0) have.push(f); else missing.push(f);
    });
    keys.forEach(k => {
      if (!FRAME.some(f => f.seg === k)) {
        const s = (window.Engine && Engine.SEGMENTS.find(x => x.key === k)) || null;
        extra.push({ seg: k, label: s ? s.name : k });
      }
    });
    return { have: have, missing: missing, extra: extra };
  }

